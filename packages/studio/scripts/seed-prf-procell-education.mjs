function serialise(value) {
  return JSON.stringify(value);
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function validateSeed() {
  assert(services.length === 9, `Expected 9 service documents, found ${services.length}.`);
  assert(comparisons.length === 6, `Expected 6 comparison documents, found ${comparisons.length}.`);

  const documents = [...services, ...comparisons];
  const documentIds = documents.map((document) => document._id);
  assert(new Set(documentIds).size === documentIds.length, 'Document IDs must be unique.');

  const serviceIds = new Set(services.map((service) => publishedId(service._id)));
  const allowedProviders = new Set(Object.values(providerIds));

  for (const service of services) {
    assert(service._id.startsWith('drafts.'), `${service.title} must use a draft ID.`);
    assert(service.status === 'proposed', `${service.title} must remain proposed.`);
    assert(service.pricingModel === 'consult', `${service.title} must remain consult-only.`);
    assert(!service.price && !service.foundingPrice && !service.rackPrice && !service.memberPrice, `${service.title} must not include public pricing.`);
    if (service.provider) {
      assert(allowedProviders.has(service.provider._ref), `${service.title} references an unverified provider ID.`);
    }
    assert(service.faqs.length >= 2, `${service.title} needs at least two FAQs.`);
    assert(service.relatedServices.length <= 3, `${service.title} has more than three related services.`);
    for (const related of service.relatedServices) {
      assert(serviceIds.has(related._ref), `${service.title} has an unknown related service reference.`);
    }
    if (service.kind === 'treatment') {
      assert(serviceIds.has(service.parentService._ref), `${service.title} has an unknown parent service reference.`);
    }
  }

  for (const comparison of comparisons) {
    assert(comparison._id.startsWith('drafts.'), `${comparison.title} must use a draft ID.`);
    assert(serviceIds.has(comparison.optionA.service._ref), `${comparison.title} option A has an unknown service reference.`);
    assert(serviceIds.has(comparison.optionB.service._ref), `${comparison.title} option B has an unknown service reference.`);
    assert(comparison.faqs.length >= 2, `${comparison.title} needs at least two FAQs.`);
  }

  const content = serialise(documents);
  for (const phrase of forbiddenPhrases) {
    assert(!phrase.test(content), `Compliance validation failed for ${phrase}.`);
  }

  console.log(`Validated ${services.length} draft services and ${comparisons.length} draft comparisons.`);
  console.log('No public prices, publication operations, destructive mutations, or unverified provider IDs are present.');
}

function resolveToken() {
  const envToken = process.env.SANITY_API_WRITE_TOKEN ?? process.env.SANITY_AUTH_TOKEN ?? process.env.SANITY_TOKEN;
  if (envToken) return envToken;
  try {
    const localEnv = readFileSync(join(process.cwd(), '.env.local'), 'utf8');
    for (const line of localEnv.split(/\r?\n/)) {
      const match = line.match(/^\s*(SANITY_API_WRITE_TOKEN|SANITY_AUTH_TOKEN|SANITY_TOKEN)\s*=\s*(.*?)\s*$/);
      if (!match || !match[2]) continue;
      const value = match[2].replace(/^(?:['\"])(.*)(?:['\"])$/, '$1');
      if (value) return value;
    }
  } catch {
    // A local environment file is optional; continue to the Sanity CLI token.
  }
  try {
    return JSON.parse(readFileSync(join(homedir(), '.config/sanity/config.json'), 'utf8')).authToken;
  } catch {
    return undefined;
  }
}

async function verifyProviders(client) {
  const providerDocs = await client.fetch(
    "*[_type == 'provider' && _id in $ids]{_id, title, lane}",
    { ids: Object.values(providerIds) },
  );
  const byId = new Map(providerDocs.map((provider) => [provider._id, provider]));
  const amber = byId.get(providerIds.amber);
  const diana = byId.get(providerIds.diana);

  assert(amber?.title === 'Amber' && amber.lane === 'advanced-aesthetics', 'Missing or mismatched provider-amber. Refusing to seed.');
  assert(diana?.title === 'Diana' && diana.lane === 'injectables-medical', 'Missing or mismatched provider-diana. Refusing to seed.');
}

async function applySeed() {
  const token = resolveToken();
  assert(token, 'No Sanity write token found. Set SANITY_API_WRITE_TOKEN, SANITY_AUTH_TOKEN, or SANITY_TOKEN, or run `sanity login`.');
  const { createClient } = await import('@sanity/client');
  const client = createClient({
    projectId: process.env.SANITY_STUDIO_PROJECT_ID ?? process.env.PUBLIC_SANITY_PROJECT_ID ?? '4e7axyi7',
    dataset: process.env.SANITY_STUDIO_DATASET ?? process.env.PUBLIC_SANITY_DATASET ?? 'production',
    apiVersion: process.env.SANITY_API_VERSION ?? process.env.PUBLIC_SANITY_API_VERSION ?? '2025-04-26',
    token,
    useCdn: false,
  });

  await verifyProviders(client);

  const documents = [...services, ...comparisons];
  const transaction = client.transaction();
  if (REPLACE) {
    const draftIdsToReplace = new Set([
      ...documents.map((document) => document._id),
      ...obsoleteDraftIds,
    ]);
    for (const id of draftIdsToReplace) transaction.delete(id);
    for (const document of documents) transaction.create(document);
  } else {
    for (const document of documents) transaction.createIfNotExists(document);
  }
  await transaction.commit();

  if (REPLACE) {
    console.log(`Atomically refreshed ${services.length} draft services and ${comparisons.length} draft comparisons managed by this script.`);
  } else {
    console.log(`Created missing drafts only: ${services.length} services and ${comparisons.length} comparisons checked.`);
    console.log('Existing documents were left untouched.');
  }
  console.log('Nothing was published.');
}

try {
  validateSeed();
  if (SHOULD_WRITE) await applySeed();
  if (VALIDATE && !SHOULD_WRITE) console.log('Static validation complete. Run with --apply to create missing drafts after provider verification.');
} catch (error) {
  console.error(`Seed validation failed: ${error.message}`);
  process.exitCode = 1;
}
